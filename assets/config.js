// CloudStatus 全域設定
// ============================================================================
// 【主要設定檔】
// 日常要調整版面、刷新、快取、逾時、事件顯示數量，優先只改這裡。
//
// 單位：
//   px    = 像素
//   ms    = 毫秒，1000 ms = 1 秒
//   true  = 開啟
//   false = 關閉
//
// 【固定版面原則】
//   寬度 < masonryMinWidth  → 單欄
//   寬度 >= masonryMinWidth → 雙欄 Masonry
//   只要是雙欄，一律階梯補位
//
// 【重要】
// 本版直接以已驗證正常的 v72 橫屏 / Masonry 為基底。
// 設定維持 v72 原本的「扁平鍵」，不再改成巢狀結構。
// ============================================================================

(function () {
  "use strict";

  window.CloudStatusConfig = Object.freeze({

    // =========================================================================
    // 01｜版本 / 服務
    // =========================================================================

    // 目前程式版本。服務模組載入時會帶上這個版本避免舊快取。
    version: "77.0.0",

    // 預期載入服務數量。新增或刪除服務時才修改。
    expectedServiceCount: 23,


    // =========================================================================
    // 02｜自動刷新
    // =========================================================================

    // 頁面保持開啟時，自動抓取新狀態的時間間隔。
    // 5 * 60 * 1000 = 5 分鐘。
    refreshInterval: 5 * 60 * 1000,

    // 從背景回到前景時，如果距離上次成功更新超過此時間，
    // 就立即重新抓取。
    // 2 * 60 * 1000 = 2 分鐘。
    foregroundRefreshThreshold: 2 * 60 * 1000,


    // =========================================================================
    // 03｜快取
    // =========================================================================

    // localStorage 快取名稱。版本更新時跟著更換。
    cacheKey: "cloudstatus-cache-v77",

    // 正常快取有效時間：15 分鐘。
    cacheMaxAge: 15 * 60 * 1000,

    // stale cache 最長保留：24 小時。
    staleCacheMaxAge: 24 * 60 * 60 * 1000,


    // =========================================================================
    // 04｜網路請求
    // =========================================================================

    // API / JSON / RSS 一般請求逾時：6.5 秒。
    fetchTimeout: 6500,

    // Reader / HTML 備援來源逾時：7.5 秒。
    readerTimeout: 7500,

    // 同時處理 fallback 來源的最大數量。
    fallbackConcurrency: 4,


    // =========================================================================
    // 05｜響應式 / Masonry
    // =========================================================================

    // 雙欄門檻。
    // < 560px  = 單欄
    // >=560px  = 雙欄 Masonry 階梯
    //
    // 手機直屏通常自然是單欄；
    // 手機橫屏、平板、桌面只要達到門檻都會雙欄階梯。
    masonryMinWidth: 560,

    // 保留 v72 原設定鍵。
    // 建議與 masonryMinWidth 保持一致。
    gridTwoColumnMinWidth: 560,

    // 桌面參考寬度。
    // 不改變「>= masonryMinWidth 就進入雙欄 Masonry」的核心規則。
    desktopMasonryMinWidth: 1180,

    // 主內容最大寬度。
    desktopMaxWidth: 1180,

    // Masonry 卡片左右 / 上下間距。
    masonryGap: 14,


    // =========================================================================
    // 06｜事件顯示
    // =========================================================================

    // 每個服務最多顯示幾筆最近已結束事件。
    recentEventLimit: 3,

    // 每個服務目前進行中的事件最多顯示幾筆。
    activeEventLimit: 20,


    // =========================================================================
    // 07｜介面顯示
    // =========================================================================

    // 是否顯示右上角來源名稱。
    // 例如：官方 API / 官方 RSS / Cloudflare Radar。
    showSourceBadge: true,

    // 是否顯示跨境線路分類。
    // 例如：中國聯通 · 普通公網。
    showRouteMeta: true
  });
})();
